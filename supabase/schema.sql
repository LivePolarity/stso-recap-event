create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.events (
  id bigint generated by default as identity primary key,
  title text not null,
  event_date date not null,
  start_time text,
  end_time text,
  notes text not null default '',
  catering jsonb not null default '{}'::jsonb,
  bar jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.admins enable row level security;
alter table public.events enable row level security;

-- The public team page can read event instructions, but cannot change them.
drop policy if exists "Anyone can read events" on public.events;
create policy "Anyone can read events" on public.events for select using (true);

-- Only user IDs explicitly inserted into admins can create/update/delete events.
drop policy if exists "Admins can insert events" on public.events;
create policy "Admins can insert events" on public.events for insert
  with check (exists (select 1 from public.admins where user_id = auth.uid()));

drop policy if exists "Admins can update events" on public.events;
create policy "Admins can update events" on public.events for update
  using (exists (select 1 from public.admins where user_id = auth.uid()))
  with check (exists (select 1 from public.admins where user_id = auth.uid()));

drop policy if exists "Admins can delete events" on public.events;
create policy "Admins can delete events" on public.events for delete
  using (exists (select 1 from public.admins where user_id = auth.uid()));

-- Admins can read the admin allow-list; other users cannot.
drop policy if exists "Admins can view admins" on public.admins;
create policy "Admins can view admins" on public.admins for select
  using (user_id = auth.uid());

